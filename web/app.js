// Baton Replay UI. Renders a handoff.json as the Director's Cut view.
// This page never runs live extraction. It only renders handoff files.

var CASES = {
  "never-executed": { file: "data/never-executed.json", label: "Never executed" },
  "completed-unreported": { file: "data/completed-unreported.json", label: "Completed, never reported" },
  "accepted-unknown": { file: "data/accepted-unknown.json", label: "Accepted, delivery unknown" },
  "real-run": { file: "data/real-run.json", label: "Real run" }
};

function esc(value) {
  return String(value == null ? "" : value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function evidenceLine(item) {
  var parts = [];
  (item.evidence || []).forEach(function (id) { parts.push(esc(id)); });
  (item.artifacts || []).forEach(function (id) { parts.push(esc(id)); });
  if (!parts.length) return "";
  return ' <span class="evidence">[' + parts.join(", ") + "]</span>";
}

function itemsHtml(items, emptyText) {
  if (!items || !items.length) return "<p>" + esc(emptyText || "None.") + "</p>";
  var out = "<ul>";
  items.forEach(function (item) {
    out += "<li>" + esc(item.claim || "") + evidenceLine(item) + "</li>";
  });
  return out + "</ul>";
}

function receiptsHtml(receipts) {
  if (!receipts || !receipts.length) return "<p>No receipts.</p>";
  var out = "";
  receipts.forEach(function (r) {
    var delivered = r.delivered === true ? "delivered" : r.delivered === false ? "not delivered" : "delivery unknown";
    out += '<div class="receipt"><span class="status">' + esc(r.provider || "") + " " + esc(r.status || "") + "</span>";
    if (r.message_id) out += " <span>message " + esc(r.message_id) + "</span>";
    out += " <span>(" + esc(delivered) + ")</span>";
    if (r.detail) out += '<div class="detail">' + esc(r.detail) + "</div>";
    out += "</div>";
  });
  return out;
}

function saidHtml(said) {
  if (!said || !said.length) return "<p>Nothing recorded.</p>";
  var out = "<ul>";
  said.forEach(function (line) { out += "<li>" + esc(line) + "</li>"; });
  return out + "</ul>";
}

function checksHtml(checks) {
  if (!checks || !checks.length) return "<p>No checks.</p>";
  var out = '<ul class="checks">';
  checks.forEach(function (c) {
    var mark = c.passed ? "PASS" : "FAIL";
    out += "<li><span class='check-mark'>" + mark + "</span>" + esc(c.name || "") +
      " (" + esc(c.kind || "") + ") " + esc(c.detail || "") + "</li>";
  });
  return out + "</ul>";
}

function validateHandoff(data) {
  if (!data || typeof data !== "object" || Array.isArray(data)) {
    throw new Error("Not a valid handoff: expected a JSON object.");
  }
  var required = ["record_id", "bundle_id", "objective", "episode", "replay",
    "completed", "needs_you", "changed", "next", "checks", "extraction"];
  required.forEach(function (key) {
    if (!(key in data)) throw new Error("Not a valid handoff: missing field " + key + ".");
  });
  ["previously", "plot_twist", "where_we_pick_up"].forEach(function (key) {
    if (!data.episode || typeof data.episode[key] !== "string") {
      throw new Error("Not a valid handoff: episode." + key + " must be a string.");
    }
  });
  if (!data.next || typeof data.next.step !== "string") {
    throw new Error("Not a valid handoff: next.step must be a string.");
  }
  if (!data.replay || !Array.isArray(data.replay.said) || !Array.isArray(data.replay.receipts)) {
    throw new Error("Not a valid handoff: replay needs said and receipts lists.");
  }
  return data;
}

function provenanceHtml(data, sourceLabel) {
  var model = (data.extraction && data.extraction.model) || "unknown";
  var tokens = "Token counts not recorded for this handoff.";
  if (data.extraction && typeof data.extraction.tokens_in === "number" &&
      typeof data.extraction.tokens_out === "number") {
    tokens = "Tokens in " + esc(data.extraction.tokens_in) + ", out " + esc(data.extraction.tokens_out) + ".";
    if (data.extraction.estimated) tokens += " Token counts are estimated.";
  }
  var made = "";
  if (model === "stub-deterministic") {
    made = "Generated by the Baton pipeline with stub extraction. Offline and deterministic. No live model call.";
  } else {
    made = "Extraction model named in this file: " + esc(model) + ". This page did not run that model.";
  }
  return "<h2>How this handoff was made</h2><p>" + esc(sourceLabel) + " " + made + "</p><p>" + tokens + "</p>";
}

function render(data, sourceLabel) {
  var ep = data.episode;
  var next = data.next;
  var contradictions = data.contradictions || [];
  var html = "";
  html += '<p class="objective">' + esc(data.objective) + "</p>";
  html += '<p class="meta">Record ' + esc(data.record_id) + " | Bundle " + esc(data.bundle_id) +
    " | Created " + esc(data.created_at) + " | Extraction model " + esc((data.extraction && data.extraction.model) || "") + "</p>";
  if (data.verdict && typeof data.verdict === "string" && data.verdict.trim()) {
    html += '<p class="verdict">' + esc(data.verdict) + "</p>";
  }
  html += '<div class="episode">';
  html += "<div><h3>Previously</h3><p>" + esc(ep.previously) + "</p></div>";
  html += '<div><h3>Plot twist</h3><hr class="red-rule"><p>' + esc(ep.plot_twist) + "</p></div>";
  html += "<div><h3>Where we pick up</h3><p>" + esc(ep.where_we_pick_up) + "</p></div>";
  html += "</div>";
  html += '<div class="panels">';
  html += '<div class="panel"><h3>What the agent said</h3>' + saidHtml(data.replay.said) + "</div>";
  html += '<div class="panel"><h3>What the receipts show</h3>' + receiptsHtml(data.replay.receipts) + "</div>";
  html += '<div class="panel"><h3>What changed</h3>' + itemsHtml(data.replay.changed, "No changes recorded.") + "</div>";
  html += "</div>";
  html += '<div class="section"><h3>Completed</h3>' + itemsHtml(data.completed, "Nothing completed.") + "</div>";
  html += '<div class="section"><h3>Failed</h3>' + itemsHtml(data.failed || [], "Nothing failed.") + "</div>";
  html += '<div class="section"><h3>Needs you</h3>' + itemsHtml(data.needs_you, "Nothing needs you.") + "</div>";
  html += '<div class="section"><h3>Next</h3><p><strong>' + esc(next.step) + "</strong> " + esc(next.reason || "") + "</p></div>";
  html += '<div class="section"><h3>Contradictions</h3>' + itemsHtml(contradictions, "No contradictions.") + "</div>";
  html += '<div class="section"><h3>Checks</h3>' + checksHtml(data.checks) + "</div>";
  document.getElementById("replay").innerHTML = html;
  document.getElementById("provenance").innerHTML = provenanceHtml(data, sourceLabel);
}

function showError(message) {
  document.getElementById("load-error").textContent = message;
}

function clearError() {
  document.getElementById("load-error").textContent = "";
}

function setActiveButton(caseKey) {
  document.querySelectorAll(".case-nav button").forEach(function (btn) {
    var isActive = btn.getAttribute("data-case") === caseKey;
    btn.classList.toggle("active", isActive);
    btn.setAttribute("aria-pressed", isActive ? "true" : "false");
  });
}

function loadCase(caseKey) {
  clearError();
  setActiveButton(caseKey);
  var info = CASES[caseKey];
  document.getElementById("replay").innerHTML = '<p class="loading">Loading ' + esc(info.label) + "…</p>";
  document.getElementById("provenance").innerHTML = "";
  fetch(info.file)
    .then(function (resp) {
      if (!resp.ok) throw new Error("Could not load " + info.file + " (HTTP " + resp.status + ").");
      return resp.json();
    })
    .then(function (data) {
      render(validateHandoff(data), "Precomputed handoff: " + info.label + ".");
    })
    .catch(function (err) {
      document.getElementById("replay").innerHTML = '<p class="error">Could not load this case. The previous replay was cleared.</p>';
      showError(err.message);
    });
}

document.querySelectorAll(".case-nav button").forEach(function (btn) {
  btn.addEventListener("click", function () { loadCase(btn.getAttribute("data-case")); });
});

function renderFile(file) {
  clearError();
  setActiveButton(null);
  var reader = new FileReader();
  reader.onload = function () {
    try {
      render(validateHandoff(JSON.parse(reader.result)), "Uploaded file: " + file.name + ".");
    } catch (err) {
      showError(err.message);
    }
  };
  reader.readAsText(file);
}

document.getElementById("render-paste").addEventListener("click", function () {
  clearError();
  setActiveButton(null);
  var text = document.getElementById("paste-input").value.trim();
  var fileInput = document.getElementById("file-input");
  if (text) {
    try {
      render(validateHandoff(JSON.parse(text)), "Pasted handoff.");
    } catch (err) {
      showError(err.message);
    }
    fileInput.value = "";
    return;
  }
  if (fileInput.files && fileInput.files[0]) {
    renderFile(fileInput.files[0]);
    return;
  }
  showError("Paste a handoff JSON first, or choose a file.");
});

document.getElementById("file-input").addEventListener("change", function (event) {
  document.getElementById("paste-input").value = "";
  var file = event.target.files && event.target.files[0];
  if (!file) return;
  renderFile(file);
});

document.getElementById("copy-skill").addEventListener("click", function () {
  var text = document.getElementById("skill-text").textContent;
  var status = document.getElementById("copy-status");
  function done(msg) { status.textContent = msg; }
  if (navigator.clipboard && navigator.clipboard.writeText) {
    navigator.clipboard.writeText(text).then(function () {
      done("Skill copied.");
    }, function () {
      done("Copy failed. Select the skill text and copy it by hand.");
    });
  } else {
    done("Clipboard unavailable here. Select the skill text and copy it by hand.");
  }
});

loadCase("completed-unreported");
